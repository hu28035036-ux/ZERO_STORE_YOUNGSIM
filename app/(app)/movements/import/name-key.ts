/**
 * 이름으로 상품을 짝지을 때 쓰는 키 — 띄어쓰기를 뗀 이름.
 *
 * 발주 사이트마다 같은 상품을 다르게 띄어 쓴다. 실물로 확인한 것들:
 *   `위시어 리얼크리스피프로틴바버터쿠키`  ↔ `위시어 리얼크리스피 프로틴바 버터쿠키`
 *   `미트리 간편한닭가슴살볶음밥차돌깍두기` ↔ `미트리 간편한 닭가슴살 볶음밥 차돌깍두기`
 *   `웅진 초록매실제로`                   ↔ `웅진 초록매실 제로`
 *
 * 글자는 같은데 공백 하나로 "미등록"이 되면 그 줄은 사람이 손으로 넣어야
 * 하고, 그 수고가 파일 반영을 하는 이유를 통째로 없앤다. 두 발주 사이트의
 * 실파일 20품목으로 재보니 **정확 일치 1건이 이 키로 12건**이 된다.
 *
 * 공백만 뗀다. 괄호·기호까지 뭉개면 서로 다른 상품이 같은 키로 붙는데,
 * 입고에서 그 사고는 **엉뚱한 상품의 재고가 늘고 화면 어디에도 티가 안 나는**
 * 형태로 나타난다 (actions.ts 머리말 참고). 키가 여럿에 걸리면 안 붙이는
 * 규칙이 마지막 안전망이고, 이 함수는 그 앞에서 욕심을 안 부리는 쪽이다.
 *
 * 전각 공백(U+3000)과 줄바꿈도 공백이다 — 엑셀에서 붙여넣은 이름에 실제로 섞여 온다.
 */
export function nameKey(name: string): string {
  return name.replace(/\s+/g, '')
}
